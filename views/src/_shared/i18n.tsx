export type TranslationKey = Key;
export type Lang = 'es' | 'en';
export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

const dictionaries: Record<Lang, Record<Key, string>> = { es, en };

export function resolveLocale(hostLocale: unknown): { lang: Lang; locale: string } {
  if (typeof hostLocale === 'string' && /^en\b/i.test(hostLocale)) return { lang: 'en', locale: hostLocale };
  if (typeof hostLocale === 'string' && /^es\b/i.test(hostLocale)) return { lang: 'es', locale: hostLocale };
  return { lang: 'es', locale: 'es-AR' };
}

export function makeTranslate(lang: Lang): Translate {
  const dict = dictionaries[lang];
  return (key, vars) => dict[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? ''));
}

type I18n = { lang: Lang; locale: string; t: Translate };
const I18nContext = createContext<I18n>({ lang: 'es', locale: 'es-AR', t: makeTranslate('es') });

export function I18nProvider({ hostLocale, children }: { hostLocale: unknown; children: ReactNode }) {
  const { lang, locale } = resolveLocale(hostLocale);
  return <I18nContext.Provider value={{ lang, locale, t: makeTranslate(lang) }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => ({ ...useContext(I18nContext), message: makeTranslate('en') });

export function statusKey(status: unknown): Key | null {
  if (status == null) return 'status.null';
  const names: Record<string, string> = { PENDING: 'pending_approval', PROVISIONAL: 'awaiting_payment', APPROVED: 'approved', PAID: 'confirmed', PAYMENT_FAST: 'approved', CANCELLED: 'cancelled', COMPLETED: 'completed' };
  const key = `status.${names[String(status)] ?? String(status)}` as Key;
  return key in es ? key : null;
}
